const verifiedAt = "2026-09-09";

function record(
  input: Omit<Opportunity, "school_scope" | "schools" | "remote" | "last_verified" | "date_added" | "difficulty" | "prestige" | "icon" | "featured" | "hidden_gem"> & {
    remote?: boolean | null;
    featured?: boolean;
  },
): Opportunity {
  const supportedFacts: OpportunitySourceReference["supports"] = [
    "academic_level",
    "class_year",
    "external_student_eligibility",
    "deadline",
    "requirements",
    "compensation",
    "program_dates",
    "location",
  ];
  const evidence = (note: string) => ({
    state: "verified_restriction" as const,
    sourceUrl: input.official_source,
    authority: "official_organization" as const,
    verifiedAt,
    note,
  });
  return {
    ...input,
    school_scope: "National",
    schools: [],
    remote: input.remote ?? null,
    last_verified: verifiedAt,
    date_added: verifiedAt,
    difficulty: null,
    prestige: null,
    icon: null,
    featured: input.featured ?? false,
    hidden_gem: false,
    metadata: {
      ...input.metadata,
      eligibilityRules: {
        ...input.metadata.eligibilityRules,
        fieldEvidence: {
          ...input.metadata.eligibilityRules?.fieldEvidence,
          academic_level: evidence("High-school stage checked against the official program page."),
          class_year: evidence("Grade or age rules checked against the official program page."),
          deadline: evidence("Current-cycle timing checked against the official program page."),
          requirements: evidence("Application requirements checked against the official program page."),
          compensation: evidence("Published cost, award, or value information checked against the official program page."),
          program_dates: evidence("Published schedule details checked against the official program page."),
          location: evidence("Published delivery format and location checked against the official program page."),
        },
      },
      sourceReferences: input.metadata.sourceReferences ?? [
        {
          url: input.official_source,
          authority: "official_organization",
          verifiedAt,
          supports: supportedFacts,
          note: "Primary official source for the current high-school opportunity record.",
        },
      ],
    },
  };
}

